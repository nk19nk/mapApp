// Импортируем библиотеку Expo для работы с локальными push-уведомлениями
import * as Notifications from 'expo-notifications';
// Импортируем интерфейс MarkerData, чтобы TypeScript знал структуру объекта маркера
import { MarkerData } from '@/types';

// Глобальная настройка: указывает операционной системе (Android/iOS), как реагировать на уведомление,
// когда приложение активно (открыто на экране). По умолчанию ОС скрывает уведомления открытого приложения.
// Notifications — имя объекта, в который мы импортировали библиотеку expo - notifications.Через него мы обращаемся ко всем её функциям.
// . — оператор доступа.Означает «возьми метод внутри объекта Notifications».
// setNotificationHandler — название метода(«установить обработчик уведомлений»).Он регистрирует глобальные правила для всего приложения.
Notifications.setNotificationHandler({
    // Асинхронная функция-обработчик, возвращающая объект с правилами отображения
// handleNotification — имя свойства(ключа) внутри объекта настроек.Библиотека Expo требует именно такое название: она будет сама вызывать эту функцию каждый раз, когда придёт уведомление.
// : — связывает имя свойства(слева) с его значением(справа).
// async — ключевое слово, делающее функцию асинхронной.Библиотека expo - notifications ожидает, что обработчик вернёт Promise(обещание), поэтому async здесь обязателен, даже если внутри нет await.
// () — пустые круглые скобки для аргументов функции.Нам не нужны детали самого уведомления, чтобы решить, показывать его или нет, поэтому скобки пустые.
// => — стрелка(синтаксис стрелочной функции).Отделяет аргументы от того, что функция возвращает.
//  ({ — очень важная пара скобок в JavaScript:
// Фигурная скобка { открывает возвращаемый объект с правилами.
// Круглая скобка(вокруг него нужна, чтобы JavaScript не перепутал { с началом обычного тела функции (где пришлось бы писать слово return ).Запись =>({ ... }) — это короткий способ сказать «сразу верни этот объект».
    handleNotification: async () => ({
        shouldShowAlert: true,  // Показывать всплывающее окно уведомления «должно ли показывать оповещение: да». Классический флаг, разрешающий показать уведомление поверх открытого приложения.
        shouldPlaySound: true,  // Проигрывать системный звук уведомления «должно ли проигрывать звук: да». Разрешает телефону издать стандартный звук уведомления.
        shouldSetBadge: false,  // Не менять красный кружок со счётчиком на иконке приложения «должно ли ставить значок: нет». Запрещает менять красный кружок с цифрой непрочитанных уведомлений на иконке приложения на рабочем столе.
        shouldShowBanner: true, // Показывать верхний баннер (требуется для новых версий ОС) «должно ли показывать баннер: да». Современная настройка (для новых версий iOS/Android), разрешающая выезжающую сверху плашку с текстом.
        shouldShowList: true,   // Сохранять уведомление в шторке уведомлений «должно ли показывать в списке: да». Разрешает оставить это уведомление в общей шторке (центре уведомлений), чтобы пользователь мог смахнуть экран сверху вниз и прочитать его позже.
    }),
});

// Функция для запроса прав на отправку уведомлений у операционной системы
// Проверяет, есть ли уже доступ, и если нет — показывает системное окно с запросом. При отказе кидает ошибку.
// export — делает функцию публичной, чтобы её можно было импортировать в других файлах(например, в app / index.tsx).
// const — объявляет константу(переменную, ссылку в которой нельзя перезаписать).
// requestNotificationPermissions — имя функции(«запросить разрешения на уведомления»).
// = — оператор присваивания.
// async — делает функцию асинхронной: она возвращает Promise и разрешает использовать внутри команду await.
// () — пустые скобки означают, что функция не принимает никаких входящих аргументов.
// => — стрелка(синтаксис стрелочной функции).
// { — открывает тело функции.
export const requestNotificationPermissions = async () => { // Публичная асинхронная функция без аргументов
    // Проверяем текущий статус разрешений и сразу вытаскиваем поле status, переименовывая его в existingStatus
//{ status: existingStatus } — деструктуризация с переименованием.Метод вернёт объект с разными полями, среди которых есть status.Мы вытаскиваем именно поле status и сразу сохраняем его в переменную под новым именем existingStatus(«существующий статус»), чтобы ниже не было конфликта имён.
// = — присваивание.
//await — ставит выполнение функции на паузу, пока операционная система не проверит настройки и не вернёт ответ.
//Notifications — объект импортированной библиотеки expo - notifications.
//.getPermissionsAsync() — метод(«получить разрешения асинхронно»).Он не показывает пользователю никаких окон, а просто тихо проверяет, даны ли права ранее.
    const { status: existingStatus } = await Notifications.getPermissionsAsync();
    // Сохраняем текущий статус в изменяемую переменную (let), так как он может обновиться ниже
// let — объявляет изменяемую переменную(в отличие от const, её значение можно перезаписать позже).
// finalStatus — имя переменной («итоговый статус»).
// = existingStatus; — записываем в неё текущий статус как начальное значение.
    let finalStatus = existingStatus;

    // Если права ещё не были выданы ранее (статус не равен 'granted')
// existingStatus — переменная с текущим статусом.
// !== — оператор строгого неравенства(«не равно» и по значению, и по типу).
// 'granted' — строка, которую возвращает Expo, когда доступ разрешён(«предоставлено»).
// { — открывает блок кода, который выполнится, только если прав ещё нет.
    if (existingStatus !== 'granted') {
        // Показываем пользователю системное окно с вопросом «Разрешить уведомления?» и ждём его ответа
// const { status } — обычная деструктуризация: достаём свойство status из объекта ответа и сохраняем в константу с тем же именем status.
// = await — ждём, пока пользователь нажмёт «Разрешить» или «Запретить» во всплывающем окне.
// Notifications.requestPermissionsAsync(); — метод(«запросить разрешения асинхронно»), который вызывает системный диалог с вопросом к пользователю.
        const { status } = await Notifications.requestPermissionsAsync();
        finalStatus = status; // Записываем новый ответ пользователя в итоговый статус
    }

    // Если после проверки и запроса пользователь всё равно не дал разрешение(Сработает, если пользователь нажал «Отклонить» или если уведомления были жёстко отключены в настройках телефона.)
    if (finalStatus !== 'granted') {
        // Выбрасываем ошибку (прерываем выполнение). Её поймает блок catch на главном экране и покажет Alert.
        throw new Error('Доступ к уведомлениям не разрешён');
    }
};

// Интерфейс (шаблон) для описания структуры объекта(из каких именно полей должен состоять объект), хранящего информацию об уже отправленном уведомлении
interface ActiveNotification {
    markerId: number;       // ID маркера из базы данных, для которого сработало уведомление
    notificationId: string; // Уникальный строковый ID уведомления, который выдала сама ОС (нужен для его удаления)/ Системные ID уведомлений обычно выглядят как длинный набор букв и цифр (например, "a1b2-c3d4"), поэтому здесь используется именно строка.
    timestamp: number;      // Время отправки уведомления в миллисекундах (отметка времени)
}

// Класс-менеджер для управления уведомлениями.
// Главная задача — вести учёт активных уведомлений, чтобы телефон не спамил ими каждые 5 секунд, пока пользователь стоит у метки.
class NotificationManager { //менеджер уведомлений
    // Приватное поле (доступно только внутри класса).
    // Map (словарь) хранит пары «ключ -> значение»: [ID маркера -> объект ActiveNotification]
// private — модификатор доступа в TypeScript(«приватный»). Означает, что к этому полю нельзя обратиться снаружи класса — только изнутри его собственных методов. Это защищает словарь от случайного изменения в другом файле.
// activeNotifications — имя поля(переменной внутри класса).
// : — отделяет имя поля от его типа.
// Map — встроенная в JavaScript структура данных «словарь» (или хэш - таблица). Она хранит данные парами «ключ → значение» и умеет мгновенно находить нужную запись по ключу.
// <number, ActiveNotification> — дженерик(уточнение типов для TypeScript): ключом всегда будет число(number, это ID маркера), а значением — объект по шаблону ActiveNotification.
    private activeNotifications: Map<number, ActiveNotification>;

    // Конструктор вызывается автоматически один раз при создании экземпляра класса (new NotificationManager())
// constructor — специальный встроенный метод класса.Он запускается автоматически ровно один раз в тот момент, когда в конце файла срабатывает команда new NotificationManager().
// () — пустые скобки, так как при создании менеджера ему не нужно передавать никаких стартовых данных.    
    constructor() {
//this — ключевое слово, которое указывает на «этот конкретный экземпляр класса». Через this методы обращаются к полям своего же класса.

//.activeNotifications — обращение к приватному полю, объявленному строкой выше.

//= new Map() — оператор new создаёт новый пустой словарь Map и сохраняет его в поле.        
        this.activeNotifications = new Map(); // Инициализируем пустой словарь
    }

    // Асинхронный метод показа уведомления. Принимает объект маркера, ничего не возвращает (Promise<void>)
//async — делает метод асинхронным(разрешает использовать await внутри).
//showNotification — имя метода. (Внутри классов слово function перед именем не пишется).
// (marker: MarkerData) — входной аргумент: метод принимает объект marker, который обязан соответствовать типу MarkerData.
// : Promise<void> — метод возвращает обещание, которое после завершения не отдаёт никаких данных(void — пустота).
    async showNotification(marker: MarkerData): Promise<void> {
        // КРИТИЧЕСКАЯ ЛОГИКА: проверяем, есть ли уже запись с таким marker.id в нашем словаре.
        // Если есть — значит пользователь уже в зоне метки и уведомление ему уже приходило.
//this.activeNotifications — обращаемся к нашему словарю.
// .has(marker.id) — встроенный метод Map(«имеет ли»).Проверяет, есть ли в словаре ключ, равный marker.id.Возвращает true или false.
// return; — мгновенно прерывает выполнение метода.Весь код ниже не сработает, и дубликат уведомления не отправится.
        if (this.activeNotifications.has(marker.id)) {
            return; // Прерываем метод, чтобы не отправлять дубликат
        }

        // Если это первый вход в радиус 50 метров — планируем отправку уведомления через ОС
        // Метод возвращает уникальный notificationId, который присвоила система
// const notificationId = — создаём константу для хранения ID, который вернёт операционная система.
//await — ждём, пока система зарегистрирует и отправит уведомление.
//Notifications.scheduleNotificationAsync(...) — метод библиотеки expo - notifications(«запланировать уведомление асинхронно»).
//content: { ... } — свойство, содержащее объект с видимой частью уведомления:
// title: "Вы рядом с меткой!" — заголовок(обычная строка в двойных кавычках).
//body: Вы находитесь рядом с сохранённой точкой.`` — основной текст(шаблонная строка в обратных кавычках).
//trigger: null — условие запуска(«триггер»).Значение null(пустота) в Expo означает «не ждать таймера, показать немедленно».
        const notificationId = await Notifications.scheduleNotificationAsync({
            content: { // Содержимое уведомления (то, что увидит пользователь)
                title: "Вы рядом с меткой!", // Заголовок
                body: `Вы находитесь рядом с сохранённой точкой.`, // Основной текст
            },
            trigger: null, // null означает «отправить немедленно», без задержки по времени
        });

        // Сохраняем информацию об отправленном уведомлении в словарь по ключу marker.id
// .set(ключ, значение) — встроенный метод Map, который добавляет новую запись в словарь.
//marker.id — первый аргумент(ключ).
// { ... } — второй аргумент(значение — объект типа ActiveNotification):
//markerId: marker.id — записываем ID маркера в поле markerId.
//notificationId — сокращённый синтаксис JavaScript.Когда имя свойства и имя переменной совпадают, вместо notificationId: notificationId пишут просто notificationId.
//timestamp: Date.now() — вызываем встроенный метод Date.now(), который возвращает текущее время в миллисекундах, и кладём его в поле timestamp.
        this.activeNotifications.set(marker.id, {
            markerId: marker.id,      // ID маркера
            notificationId,           // Системный ID уведомления (сокращённая запись notificationId: notificationId)
            timestamp: Date.now(),    // Текущее время в миллисекундах
        });
    }

    // Асинхронный метод удаления уведомления. Вызывается, когда пользователь уходит дальше 50 метров от маркера
//Асинхронный метод с именем removeNotification. Принимает один аргумент — числовой markerId, и ничего не возвращает (Promise<void>).
    async removeNotification(markerId: number): Promise<void> {
        // Ищем в словаре активное уведомление по ID маркера
//const notification = — константа для найденной записи.
//.get(markerId) — встроенный метод Map(«получить»).Ищет в словаре объект по ключу markerId.Если запись найдена — вернёт её, если нет — вернёт undefined.
        const notification = this.activeNotifications.get(markerId);
        // Если уведомление для этого маркера действительно было активно
//Проверка на существование. В JavaScript, если внутри if лежит объект — это true (условие выполняется); если там undefined — это false (блок пропускается).
        if (notification) {
            // Отменяем/удаляем уведомление из системы по его notificationId
// await — ждём ответа от системы.
//Notifications.cancelScheduledNotificationAsync(...) — метод Expo(«отменить запланированное уведомление асинхронно»).
//notification.notificationId — передаём системный ID, который мы ранее сохранили в словаре, чтобы ОС знала, какое именно уведомление убрать.
            await Notifications.cancelScheduledNotificationAsync(notification.notificationId);
            // Удаляем запись из нашего словаря. Теперь, если пользователь снова подойдёт к метке, уведомление придёт заново.
            //.delete(markerId) — встроенный метод Map, который полностью удаляет пару «ключ → значение» из словаря по указанному markerId.
            this.activeNotifications.delete(markerId);
        }
    }
}

// Создаём и экспортируем единственный объект/экземпляр класса (паттерн Singleton).
// Все файлы приложения будут обращаться к одному и тому же объекту с общим словарём активных уведомлений.
export const notificationManager = new NotificationManager();
// export — делает переменную публичной.Благодаря этому её можно импортировать в других файлах проекта(например, в app / index.tsx через import { notificationManager } from ...).
// const — объявляет константу.Саму ссылку notificationManager нельзя будет перезаписать другим объектом (хотя данные внутри её словаря Map менять можно).
// notificationManager — имя готового объекта.Обратите внимание на регистр: сам класс называется с большой буквы(NotificationManager), а конкретный экземпляр — с маленькой(notificationManager).Это стандартное правило именования в TypeScript / JavaScript.
// = — оператор присваивания.Сохраняет созданный справа объект в переменную слева.
//new — специальный оператор создания экземпляра класса.Он выделяет память под новый объект, автоматически запускает метод constructor() внутри класса(который создаёт пустой new Map()) и возвращает готовый объект.
//NotificationManager() — обращение к конструктору нашего класса.Круглые скобки() запускают его; они пустые, потому что наш constructor() не требует входных аргументов.

//Мы специально не экспортируем сам класс NotificationManager, а сразу создаём один объект и экспортируем его. В программировании это называется паттерном Singleton (Одиночка)
//В JavaScript / TypeScript модули кешируются: сколько бы разных файлов ни сделали import { notificationManager }, они все получат ссылку на один и тот же объект с одним общим словарём activeNotifications.Если бы каждый экран создавал свой new NotificationManager(), у каждого был бы свой отдельный словарь, и защита от дублирующихся уведомлений перестала бы работать.