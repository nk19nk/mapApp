import * as Location from 'expo-location';

// Функция для запроса прав у операционной системы (Android/iOS)
//Вызывает системное окошко и спрашивает у пользователя, можно ли приложению использовать GPS. Если пользователь отказывает — кидает ошибку.
export const requestLocationPermissions = async () => {
    // requestForegroundPermissionsAsync запрашивает доступ к GPS, пока приложение открыто
//Ждем, пока система покажет пользователю всплывающее окно "Разрешить приложению доступ к геопозиции?" и пользователь нажмет кнопку. Foreground означает, что мы просим доступ только тогда, когда приложение открыто на экране.
    const { status } = await Location.requestForegroundPermissionsAsync();
    // Если пользователь нажал "Отклонить" - выбрасываем ошибку, чтобы её поймал try/catch
    if (status !== 'granted') {
        throw new Error('Доступ к местоположению не разрешён');//Выбрасываем ошибку (прерываем выполнение). Эту ошибку поймает блок catch на главном экране и покажет красивый Alert.
    }
};

