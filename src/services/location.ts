// Ручная математическая реализация функции расчета расстояния на сфере (Земле). Формула Хаверсина
export const calculateDistance = (
//Принимает 4 числа: широту и долготу первой точки (пользователя) и широту и долготу второй точки (маркера).
    lat1: number,
    lon1: number,
    lat2: number,
    lon2: number
): number => {//Функция гарантированно вернет число (расстояние)
    // Константа: радиус Земли в метрах (6 371 000)
    const R = 6371e3;
    // Перевод широт в радианы. Это обязательно, так как функции Math.sin и Math.cos в программировании работают только с радианами.
    const φ1 = (lat1 * Math.PI) / 180;
    const φ2 = (lat2 * Math.PI) / 180;
    // Разница широт в радианах
    const Δφ = ((lat2 - lat1) * Math.PI) / 180;
    // Разница долгот в радианах
    const Δλ = ((lon2 - lon1) * Math.PI) / 180;

    // Квадрат половины хорды (формула Хаверсина)
    const a =
        Math.sin(Δφ / 2) * Math.sin(Δφ / 2) +
        Math.cos(φ1) * Math.cos(φ2) * Math.sin(Δλ / 2) * Math.sin(Δλ / 2);
    // Угловое расстояние в радианах
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));

    // Итоговое расстояние в метрах. Умножаем радиус Земли на угловое расстояние
    return R * c;
};