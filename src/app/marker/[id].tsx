// Импортируем хуки React:
// useState — для хранения локальных данных экрана (маркер, фото, статус загрузки)
// useEffect — для автоматического запуска загрузки данных при открытии экрана
import { useEffect, useState } from 'react';

// Импортируем базовые компоненты интерфейса React Native:
// View — контейнер-обёртка, Text — вывод текста, Button — кнопка,
// Alert — системные всплывающие окна с предупреждениями и вопросами,
// StyleSheet — оптимизированная таблица стилей, ActivityIndicator — спиннер загрузки
import { ActivityIndicator, Alert, Button, StyleSheet, Text, View } from 'react-native';

// Импортируем хуки навигации Expo Router:
// useLocalSearchParams — считывает динамические параметры из URL (в нашем случае [id])
// useRouter — даёт объект управления переходами (например, router.back())
import { useLocalSearchParams, useRouter } from 'expo-router';

// Импортируем всю библиотеку выбора фото из галереи под именем ImagePicker
//звёздочка * as ImagePicker собирает всё содержимое библиотеки работы с галереей в один объект с именем ImagePicker
import * as ImagePicker from 'expo-image-picker';

// Импортируем наш кастомный хук БД для получения методов работы с SQLite(@/ — сокращённый путь к корню проекта)
import { useDatabase } from '@/contexts/DatabaseContext';

// Импортируем переиспользуемый UI-компонент списка изображений
import ImageList from '@/components/ImageList';

// Импортируем TypeScript-интерфейсы для строгой типизации данных маркера и картинки
import { MarkerData, MarkerImage } from '@/types';

// Главный компонент экрана (export default обязателен для маршрутов в Expo Router)
//Инициализация компонента, параметров и состояний
export default function MarkerScreen() {
    // Получаем объект роутера для возврата на предыдущий экран
    const router = useRouter();//объект навигации, который возвращает хук useRouter()

    // Извлекаем параметр id из URL. Дженерик <{ id: string }> подсказывает TypeScript,
    // что из маршрута обязательно придёт строковое поле id
    //{ id } — деструктуризация: достаём свойство id из объекта параметров маршрута.
    //useLocalSearchParams — хук Expo Router, считывающий динамическую часть адреса [id].
    //<{ id: string }> — дженерик TypeScript: уточняем, что параметр id приходит строго как строка(string).
    const { id } = useLocalSearchParams<{ id: string }>();

    // Конвертируем строковый id в число,
    // чтобы корректно сравнивать его с числовыми ID из базы данных SQLite
    const markerId = Number(id);

    // Деструктуризация: забираем из контекста базы данных только те 5 методов,
    // которые реально нужны на этом экране
    const { getMarkers, getMarkerImages, addImage, deleteImage, deleteMarker } = useDatabase();

    // Состояние для текущего маркера: либо объект MarkerData, либо null (пока не загружен или не найден)
    const [marker, setMarker] = useState<MarkerData | null>(null);//хранит найденный маркер (MarkerData) или null (знак | означает «ИЛИ»). Начальное значение — null
    // Состояние для массива фотографий маркера (изначально пустой массив [])
    const [images, setImages] = useState<MarkerImage[]>([]);
    // Флаг загрузки: изначально true, чтобы пользователь видел спиннер, пока идут SQL-запросы
    const [loading, setLoading] = useState(true);//boolean

    // Асинхронная функция загрузки данных маркера и его картинок из SQLite
    const loadData = async () => {
        try {
            // 1. Загружаем все маркеры из таблицы markers
            const allMarkers = await getMarkers();//await ждёт ответа от SQLite и сохраняет массив всех маркеров в allMarkers
            // 2. Ищем нужный маркер по совпадению id.
            // .find(...) — метод массива, который перебирает элементы по одному(m) и возвращает первый, для которого условие истинно.
            // (m) => m.id === markerId — стрелочная функция - проверка: === (строгое равенство) сверяет id маркера с нашим текущим markerId.
            // Если .find() ничего не нашёл (вернул undefined), оператор ?? подставит null
            setMarker(allMarkers.find((m) => m.id === markerId) ?? null);
            // 3. Загружаем все картинки из таблицы marker_images, привязанные к этому markerId
            setImages(await getMarkerImages(markerId));
        } catch (error) {
            // Если любой из запросов к БД упал с ошибкой — уведомляем пользователя через системный Alert
            Alert.alert('Ошибка', 'Не удалось загрузить данные из базы');//системное окно с заголовком и текстом
        } finally {
            // Блок finally сработает в любом случае (и при успехе, и при ошибке) —
            // выключаем индикатор загрузки, чтобы экран не завис на спиннере навсегда
            setLoading(false);//блок, который выполняется всегда (и после успеха, и после ошибки), выключая спиннер
        }
    };

    // Запускаем функцию loadData() сразу при открытии экрана и повторно, если изменится параметр id в URL
//useEffect — хук, запускающий loadData() при открытии экрана.
// [id] — массив зависимостей: если в URL придёт другой id, данные загрузятся заново
    useEffect(() => {
        loadData();
    }, [id]);

    // Функция безопасного возврата на экран карты
    const goBack = () => {
        try {
            // Снимает текущий экран со стека навигации и возвращает на предыдущий (index.tsx)
            router.back();//метод навигатора, закрывающий текущий экран и возвращающий пользователя на предыдущий
        } catch (error) {
            Alert.alert('Ошибка', 'Не удалось вернуться назад');
        }
    };

    // Асинхронная функция добавления фотографии из галереи устройства
    const pickImage = async () => {
        try {
            // Запрашиваем у ОС разрешение на доступ к медиатеке (галерее)
            const permission = await ImagePicker.requestMediaLibraryPermissionsAsync();
            // Если пользователь запретил доступ (granted === false)
            if (!permission.granted) {//свойство granted - «разрешено»
                Alert.alert('Нет доступа', 'Разрешите доступ к галерее в настройках');
                return; // Прерываем функцию, галерею не открываем
            }

            // Открываем системный выбор файлов:
            //launchImageLibraryAsync — открывает системную галерею
            // mediaTypes: ['images'] — фильтр: показывать только изображения (без видео), разрешаем выбирать только картинки (без видео)
            // quality: 0.7 — коэффициент сжатия (от 0 до 1), где 0.7 означает 70% качества, сжимаем изображение до 70% качества для экономии памяти
            const result = await ImagePicker.launchImageLibraryAsync({
                mediaTypes: ['images'],
                quality: 0.7,
            });

            // Проверяем, что пользователь действительно выбрал фото, а не нажал «Отмена»
            //canceled (переводится как «отменено») — это логическое свойство (true или false) внутри объекта result
            //Без неё, при закрытии галереи без выбора фото, приложение упало бы с ошибкой при попытке прочитать result.assets[0].uri, потому что assets был бы равен null
            if (!result.canceled) {//(canceled === false)
                // Берём путь (uri) к первому выбранному файлу (assets[0].uri) и сохраняем его в SQLite
                //result.assets — массив выбранных файлов.
                // [0] — обращение к первому(нулевому по индексу) элементу массива.
                // .uri — текстовый путь к этому файлу на устройстве.
                await addImage(markerId, result.assets[0].uri);
                // Перезагружаем данные из БД, чтобы новая картинка сразу появилась на экране
                await loadData();
            }
        } catch (error) {
            Alert.alert('Ошибка', 'Не удалось добавить изображение');
        }
    };

    // Обработчик удаления одной картинки (передаётся как проп onDelete в компонент ImageList)
    const handleDeleteImage = async (imageId: number) => {//функция принимает один числовой аргумент — ID удаляемой картинки
        try {
            // Удаляем запись о картинке из БД таблицы marker_images по её первичному ключу imageId
            await deleteImage(imageId);
            // Обновляем список на экране, чтобы удалённое фото исчезло
            await loadData();
        } catch (error) {
            Alert.alert('Ошибка', 'Не удалось удалить изображение');
        }
    };

    // Обработчик удаления всего маркера с защитой от случайного нажатия
    const handleDeleteMarker = () => {
        // Вызываем системный диалог с заголовком, текстом и массивом из двух кнопок
        // Alert — встроенный модуль из библиотеки react - native, который умеет вызывать нативные(системные) всплывающие диалоговые окна Android и iOS.
        // alert(...) — метод, который запускает показ диалогового окна.Он принимает три аргумента через запятую
        // первый аргумент(строка): жирный заголовок вверху окна.
        // второй аргумент(строка): основной текст - пояснение под заголовком.
        // [ — открывающая квадратная скобка третьего аргумента: массива кнопок.Каждый элемент этого массива — объект { ... }, описывающий одну кнопку.
        Alert.alert('Удаление', 'Удалить маркер вместе со всеми изображениями?', [
            // 1-я кнопка: просто закрывает окно (style: 'cancel')
            { text: 'Отмена', style: 'cancel' },
            // 2-я кнопка: подтверждение опасного действия
            {
                text: 'Удалить',
                style: 'destructive', // Визуально выделяет кнопку красным (стандарт на iOS)
                //async — делает функцию асинхронной, чтобы внутри можно было использовать await для ожидания ответа от базы данных.
                onPress: async () => {//свойство-обработчик, которое хранит функцию, запускаемую ровно в момент нажатия на кнопку «Удалить»
                    try {
                        // Удаляем маркер в транзакции SQLite (все его фото удаляются вместе с ним)
                        await deleteMarker(markerId);
                        // После удаления оставаться на экране несуществующего маркера нельзя — уходим на карту
                        goBack();
                    } catch (error) {
                        Alert.alert('Ошибка', 'Не удалось удалить маркер');
                    }
                },
            },
        ]);
    };

    // 1-й сценарий отрисовки (ранний возврат): пока данные грузятся — показываем спиннер
    if (loading) {//пока loading === true, рисуется только контейнер с <ActivityIndicator size="large"/>
        return (
            <View style={styles.container}>
                <ActivityIndicator size="large" />
            </View>
        );
    }

    // 2-й сценарий отрисовки (ранний возврат): если загрузка завершилась, но маркер в БД не найден
    if (!marker) {//если загрузка кончилась, но marker === null (!marker), показывается текст «Маркер не найден» и кнопка возврата
        return (
            <View style={styles.container}>
                <Text>Маркер не найден</Text>
                <Button title="Назад к карте" onPress={goBack} />
            </View>
        );
    }

    // 3-й сценарий (основной UI): маркер найден, отображаем все его данные и кнопки управления
    return (
        // корневой контейнер экрана
        <View style={styles.container}>
            {/* Секция координат маркера */}
            <Text style={styles.title}>Местоположение</Text>
            {/*фигурные скобки вставляют JS-выражение в текст; метод.toFixed(5) округляет число до 5 знаков после запятой (точность ~1 метр) и превращает в строку */}
            <Text>Широта: {marker.latitude.toFixed(5)}</Text>
            <Text>Долгота: {marker.longitude.toFixed(5)}</Text>

            {/* Секция изображений: в скобках динамически выводится количество фото (images.length) */}
            <Text style={styles.title}>Изображения ({images.length})</Text>
            {/* Контейнер с flex: 1 занимает всё доступное место между заголовком и нижними кнопками */}
            <View style={styles.list}>
                {/* Передаём массив картинок и коллбэк удаления в дочерний компонент ImageList */}
                {/* рендер дочернего компонента, которому через пропсы передаются массив images и ссылка на функцию handleDeleteImage */}
                <ImageList images={images} onDelete={handleDeleteImage} />
            </View>

            {/* Панель кнопок управления внизу экрана */}
            <Button title="Добавить изображение" onPress={pickImage} />
            {/* Пустой View высотой 8 пикселей используется как простой вертикальный разделитель между кнопками */}
            <View style={{ height: 8 }} />
            {/* Кнопка удаления маркера с красной заливкой (color="red") */}
            <Button title="Удалить маркер" color="red" onPress={handleDeleteMarker} />
            <View style={{ height: 8 }} />
            {/* Кнопка ручного возврата на карту (так как в _layout.tsx мы скрыли стандартную стрелку «Назад») */}
            <Button title="Назад к карте" onPress={goBack} />
        </View>
    );
}

// Таблица стилей компонента, оптимизированный объект стилей
const styles = StyleSheet.create({
    // Основной контейнер: занимает весь экран (flex: 1), отступы по бокам 16px, сверху 120px
    //flex: 1 (на весь экран), padding: 16 (внутренние отступы 16px со всех сторон), paddingTop: 120 (увеличенный отступ сверху 120px, перекрывающий общий padding)
    container: { flex: 1, padding: 16, paddingTop: 120 },
    // Заголовки секций: крупный жирный шрифт и вертикальные отступы
    //fontSize: 18 (размер шрифта), fontWeight: 'bold' (жирное начертание), marginTop: 12 (внешний отступ сверху)
    title: { fontSize: 18, fontWeight: 'bold', marginTop: 12, marginBottom: 4 },
    // Контейнер списка фото: flex: 1 растягивает его, чтобы кнопки всегда оставались внизу экрана
    //flex: 1 (растягивается на всё оставшееся пространство по вертикали, прижимая кнопки к низу экрана), marginBottom: 12 (отступ снизу до кнопок)
    list: { flex: 1, marginBottom: 12 },
});