// Импортируем базовые UI-компоненты из React Native:
// View — контейнер (аналог <div> в веб-разработке) для группировки элементов
// Text — компонент для вывода любого текста на экран
// Button — стандартная системная кнопка
// ActivityIndicator — крутящийся спиннер (индикатор загрузки)
// StyleSheet — инструмент для создания и оптимизации стилей
import { View, Text, Button, ActivityIndicator, StyleSheet } from 'react-native';

// Импортируем компонент Stack из expo-router(библиотеки маршрутизации).
// Stack-навигатор работает как стопка карт: новый экран кладётся поверх старого,
// а при возврате назад верхний экран снимается со стопки.
import { Stack } from 'expo-router';

// Импортируем нашу обёртку DatabaseProvider и кастомный хук useDatabase из контекста БД
import { DatabaseProvider, useDatabase } from '@/contexts/DatabaseContext';

// Внутренний (не экспортируемый) компонент, который отвечает за проверку состояния БД
// и отображение либо экрана загрузки, либо ошибки, либо самой навигации
//function — объявляет React - компонент.Здесь нет export, потому что этот компонент используется только внутри этого файла
function AppStack() {
  // Деструктуризация: вызываем хук useDatabase() и достаём из контекста три свойства:
  // isLoading (идёт ли загрузка), error (объект ошибки или null), retry (функция повтора)
  const { isLoading, error, retry } = useDatabase();

  // 1-й сценарий (ранний возврат): если база данных ещё открывается или создаёт таблицы
  if (isLoading) {
    // Прерываем функцию и возвращаем экран загрузки вместо карты
    return (
      // Контейнер View, к которому применён стиль styles.center (выравнивание по центру)
      <View style={styles.center}>
        {/* Индикатор загрузки большого размера (size="large") */}
        <ActivityIndicator size="large" />
        {/* Подпись под индикатором */}
        <Text>Подготовка базы данных...</Text>
      </View>
    );
  }

  // 2-й сценарий (ранний возврат): если при инициализации БД произошла ошибка (error !== null)
  if (error) {
    return (
      <View style={styles.center}>
        {/* Выводим текст ошибки; {error.message} подставляет конкретное описание из объекта Error */}
        <Text style={styles.errorText}>Ошибка базы данных: {error.message}</Text>
        {/* Кнопка: title — надпись на кнопке, onPress={retry} — при нажатии вызовет retry()
            из DatabaseContext, что увеличит счётчик attempt и перезапустит подключение к БД 
            обработчик нажатия: передаём ссылку на функцию retry (без скобок (), чтобы она вызвалась только при клике, а не сразу при отрисовке)*/}
        <Button title="Повторить" onPress={retry} />
      </View>
    );
  }

  // 3-й сценарий (основной): если загрузки нет и ошибок нет — база готова к работе.
  // Возвращаем Stack-навигатор со списком экранов приложения.
  return (
    //контейнер стековой навигации(экраны накладываются друг на друга как стопка карт)
    <Stack>
      {/* Stack.Screen — настройка конкретного экрана внутри стека. 
      name="index" — связывает настройку с файлом app/index.tsx.
      options={{ title: 'Карта' }} — передаёт объект настроек шапки. Двойные фигурные скобки {{ ... }} означают: внешние {} — вставка JS в JSX, внутренние {} — сам объект со свойством title
      Регистрируем главный экран (файл app/index.tsx) и задаём текст в верхней шапке */}
      <Stack.Screen name="index" options={{ title: 'Карта' }} />

      {/* Регистрируем динамический экран деталей маркера (файл app/marker/[id].tsx).
          name="marker/[id]" — связывает настройку с динамическим маршрутом app/marker/[id].tsx
          options — объект настроек шапки (двойные фигурные скобки: внешние для JS в JSX, внутренние — сам объект):
          title — заголовок шапки;
          headerBackVisible: false — скрывает стандартную системную стрелку «Назад» */}
      <Stack.Screen
        name="marker/[id]"
        options={{ title: 'Детали маркера', headerBackVisible: false }}
      />
    </Stack>
  );
}

// Главный корневой компонент. export default обязателен для Expo Router,
// чтобы фреймворк автоматически распознал этот файл как корневой макет всего приложения.
export default function RootLayout() {
  return (
    // Оборачиваем AppStack в DatabaseProvider.
    // Всё, что находится внутри <DatabaseProvider>...</DatabaseProvider>, передаётся туда как prop children
    // и получает доступ к общей базе данных через useDatabase().
    //Благодаря этому AppStack и все экраны внутри него получают доступ к базе данных
    <DatabaseProvider>
      <AppStack />
    </DatabaseProvider>
  );
}

// Создаём таблицу стилей с помощью StyleSheet.create (метод React Native, который проверяет корректность стилей и оптимизирует их передачу в нативный интерфейс)
const styles = StyleSheet.create({
  // Стиль для центрирования содержимого на весь экран:
  // flex: 1 — растянуть контейнер на всю доступную высоту и ширину экрана, растягивает блок на всё свободное пространство экрана
  // justifyContent: 'center' — выровнять дочерние элементы по центру вертикально (основная ось)
  // alignItems: 'center' — выровнять по центру горизонтально (поперечная ось)
  // padding: 20 — внутренний отступ 20 пикселей со всех сторон
  center: { flex: 1, justifyContent: 'center', alignItems: 'center', padding: 20 },

  // Стиль для текста ошибки:
  // marginBottom: 12 — внешний отступ снизу 12 пикселей (чтобы текст не прилипал к кнопке)
  // textAlign: 'center' — выравнивание строк текста по центру
  errorText: { marginBottom: 12, textAlign: 'center' },
});