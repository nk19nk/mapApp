// Импортируем базовые компоненты для построения интерфейса из React Native
// FlatList - оптимизированный список для длинных массивов данных (рендерит только то, что видно на экране)
// Импортируем базовые компоненты интерфейса из React Native:
// View — контейнер-обёртка для группировки элементов
// Image — компонент для отображения картинок (из памяти устройства или из интернета)
// Button — стандартная системная кнопка
// FlatList — оптимизированный прокручиваемый список с виртуализацией (рендерит только видимые элементы), 
// оптимизированный список для длинных массивов данных (рендерит только то, что видно на экране)
// StyleSheet — инструмент для создания и оптимизации таблицы стилей
// Text — компонент для вывода текста
import { View, Image, Button, FlatList, StyleSheet, Text } from 'react-native';
// Импортируем тип данных для отдельного изображения из нашего файла типов, TypeScript-интерфейс MarkerImage (описывает структуру объекта фото: id, marker_id, uri)
import { MarkerImage } from '@/types';

// Описываем интерфейс Props (свойства), строгий шаблон объекта, которые этот компонент принимает от родителя (MarkerScreen)
// Интерфейс пропсов: строго описывает, какие данные и функции родительский экран (MarkerScreen)
// обязан передать в этот компонент
//properties — свойства, которые компонент получает от родителя
interface Props {
    // images — имя пропа.
    // : MarkerImage[] — тип: массив([]) объектов формата MarkerImage
    images: MarkerImage[]; // Массив изображений, которые нужно отобразить, Массив фотографий из SQLite для отрисовки
    onDelete: (imageId: number) => void; // Функция обратного вызова (колбэк) для удаления картинки(принимает числовой ID фото, ничего не возвращает)
}

// Экспортируем функциональный компонент ImageList
// В параметрах сразу делаем деструктуризацию пропсов { images, onDelete }
// export default — экспорт по умолчанию(позволяет импортировать компонент в[id].tsx без фигурных скобок)
//Фигурные скобки { images, onDelete } прямо внутри круглых скобок функции — это деструктуризация объекта.Она автоматически «распаковывает» этот общий объект props и создаёт две обычные локальные переменные images и onDelete.
//Без деструктуризации код выглядел бы так — приходилось бы везде дописывать props.
// Вот что на самом деле получает функция ImageList:
// props = {
//     images: [{ id: 1, uri: '...' }, ... ],
//     onDelete: handleDeleteImage
// }
export default function ImageList({ images, onDelete }: Props) {
    // Если массив картинок пуст (длина равна 0)
    if (images.length === 0) {
        // Возвращаем простой текстовый блок с сообщением для пользователя
        return <Text style={styles.empty}>Изображений пока нет</Text>;
    }

    // Если картинки есть, возвращаем компонент FlatList, рендерим оптимизированный список FlatList
    return (
        //<FlatList — открывающий тег оптимизированного списка. Ему передаются три обязательных пропа:
        <FlatList
            // Передаем массив данных, который нужно отрисовать
            // Источник данных — массив объектов MarkerImage
            data={images}//проп, в который передаётся исходный массив данных (images)
            // Функция, которая создает уникальный ключ (string) для каждого элемента списка
            // Извлекает уникальный id для каждого элемента (нужно React для оптимизации перерисовок).
            //(item) => — стрелочная функция; в переменную item попадает один объект MarkerImage из массива.
            // item.id в SQLite — это число, переводим его в строку через .toString(), так как FlatList требует строковый ключ
            keyExtractor={(item) => item.id.toString()}
            // Функция, которая описывает, как должен выглядеть один элемент списка (одна картинка)
            // Шаблон отрисовки одного элемента списка.
            // FlatList передаёт сюда объект { item, index, separators }, из которого мы деструктуризацией забираем только item
            //({ item }) — деструктуризация аргумента: FlatList передаёт внутрь служебный объект { item, index, separators }, и мы фигурными скобками сразу вытаскиваем оттуда только свойство item (саму картинку).
            renderItem={({ item }) => (
                // Контейнер для одной картинки и её кнопки удаления(кнопка под ней)
                <View style={styles.item}>
                    {/* Само изображение. uri - это локальный путь к файлу в памяти устройства */}
                    {/* Компонент изображения:
                        source={{ uri: item.uri }} — передаём путь к файлу в памяти телефона;
                        {{ ... }} — двойные фигурные скобки: внешние {} открывают JavaScript в JSX, внутренние {} создают объект { uri: ... }.
                        style={styles.image} — задаём размеры (без явных width/height картинка по URI в RN не отобразится) */}
                    <Image source={{ uri: item.uri }} style={styles.image} />
                    {/* Кнопка удаления. При нажатии вызывает функцию onDelete, передавая id именно этой картинки */}
                    {/* Кнопка удаления конкретной картинки:
                        color="red" — выделяет кнопку красным;
                        onPress — обработчик нажатия.
                        () => — анонимная стрелочная функция-обёртка, чтобы удаление сработало только при клике, а не сразу при отрисовке списка.
                        onDelete(item.id) — вызывает родительскую функцию из [id].tsx, передавая ей id конкретной картинки. */}
                    <Button title="Удалить" color="red" onPress={() => onDelete(item.id)} />
                </View>
            )}
        />
    );
}

// Объект со стилями компонента
const styles = StyleSheet.create({
    // Стиль для текстового сообщения, когда список пуст (выравнивание по центру, отступ сверху, серый цвет)
    empty: { textAlign: 'center', marginTop: 20, color: 'gray' },
    // Отступ снизу для каждого элемента списка, чтобы картинки не слипались
    // Нижний внешний отступ 16px у каждой карточки, чтобы фотографии визуально не слипались
    item: { marginBottom: 16 },
    // Стиль самой картинки: занимает 100% ширины контейнера, высота жестко 200px, скругленные углы
    // marginBottom: 4 — небольшой зазор между картинкой и кнопкой «Удалить»
    image: { width: '100%', height: 200, borderRadius: 8, marginBottom: 4 },
});