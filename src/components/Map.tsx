// Импортируем инструмент StyleSheet из React Native для создания оптимизированной таблицы стилей
import { StyleSheet } from 'react-native';

// Импортируем из библиотеки react-native-maps:
// MapView (экспорт по умолчанию) — сам компонент интерактивной карты
// Marker — компонент булавки (метки) на карте
// Region — тип TypeScript, описывающий область видимости камеры (центр + масштаб)
import MapView, { Marker, Region } from 'react-native-maps';

// Импортируем интерфейс MarkerData, чтобы типизировать входящий массив маркеров
import { MarkerData } from '@/types';

// Интерфейс пропсов: строго описывает, какие данные и коллбэки родительский экран (index.tsx)
// обязан передать в этот компонент карты
interface MapComponentProps {
    //markers — имя пропа.
    //: MarkerData[] — тип: массив([]) объектов формата MarkerData
    markers: MarkerData[];// Массив маркеров из SQLite для отрисовки
    // onMapReady — имя пропа - функции.
    // () — функция не принимает аргументов.
    // => void — стрелка означает «возвращает», void — «ничего не возвращает» (пустота)
    onMapReady: () => void;// Коллбэк, вызываемый после полной загрузки карты
    //вертикальная черта | означает «ИЛИ»: функция может быть обычной (void) или асинхронной (Promise<void>)
    onLongPress: (latitude: number, longitude: number) => void | Promise<void>; // Коллбэк долгого нажатия (может быть async)
    onMarkerPress: (id: number) => void;// Коллбэк нажатия на конкретный маркер (передаёт его ID)
}

// Экспортируем компонент по умолчанию.
// В параметрах сразу делаем деструктуризацию пропсов { markers, onMapReady, onLongPress, onMarkerPress }
//деструктуризация пропсов: вместо того чтобы принимать один общий объект props и писать props.markers, мы сразу вытаскиваем 4 нужных свойства в отдельные переменные
//: MapComponentProps — привязывает эти пропсы к нашему интерфейсу (если родитель забудет передать хоть одно свойство, TypeScript сразу покажет ошибку)
export default function MapComponent({ markers, onMapReady, onLongPress, onMarkerPress }: MapComponentProps) {
    // Начальная область камеры (центр — Пермь).
    // Используется только один раз при первом открытии карты (initialRegion не мешает пользователю двигать карту дальше)
    //: Region — строгая типизация из react-native-maps (обязывает указать все 4 поля координат и масштаба)
    const initialRegion: Region = {
        latitude: 58.0105,  // Широта центра экрана
        longitude: 56.2502, // Долгота центра экрана
        latitudeDelta: 0.1, // Высота видимой области в градусах (масштаб по вертикали)(чем меньше число, тем сильнее приближение)
        longitudeDelta: 0.1,// Ширина видимой области в градусах (масштаб по горизонтали)
    };

    return (
        // Основной компонент нативной карты (Google Maps на Android / Apple Maps на iOS)
        //открывающий тег компонента карты. Внутри передаются пропсы (настройки)
        <MapView
            style={styles.map}// Растягиваем карту на весь контейнер (flex: 1)
            showsUserLocation={true}// Показываем синюю точку текущего местоположения пользователя
            showsMyLocationButton={true}  // Показываем системную кнопку-прицел для центрирования камеры на пользователе
            initialRegion={initialRegion} //передаёт наш объект стартовых координат, Задаём стартовую позицию и масштаб камеры
            onMapReady={onMapReady}// Пробрасываем событие готовности карты родителю (чтобы скрыть спиннер загрузки)
            // Встроенное событие долгого нажатия на карту:
            // e (event) — нативное событие касания; внутри e.nativeEvent.coordinate лежат точные GPS-координаты точки нажатия
            onLongPress={(e) =>//принадлежит библиотеке карт, свойство (событие) самого компонента <MapView> из библиотеки react-native-maps
                // Вызываем родительскую функцию и передаём ей чистые числа (широту и долготу)
                onLongPress(//функция из главного экрана, функция, которую вы сами описали в интерфейсе MapComponentProps и передали в <MapComponent> с главного экрана app/index.tsx
                    //достаём точные GPS-координаты точки, куда пользователь зажал палец на карте
// e(сокращение от event — событие) — главный объект события, который библиотека react - native - maps автоматически создаёт и передаёт в onLongPress в момент долгого нажатия.
// .nativeEvent — «нативное событие».В React Native все касания сначала обрабатываются самой операционной системой(Android или iOS), а React оборачивает их в свою обёртку.Внутри.nativeEvent лежат реальные данные, пришедшие напрямую от нативного движка карт(Google Maps / Apple Maps).
// .coordinate — вложенный объект с географическими координатами именно той точки на карте, куда нажал палец. (Внутри nativeEvent есть и другие данные, например.position — координаты в пикселях экрана X / Y, но для сохранения маркера нам нужны именно географические координаты).
                    e.nativeEvent.coordinate.latitude,
                    e.nativeEvent.coordinate.longitude
                )
            }
        >
            {/* Проходим методом .map() по массиву markers и превращаем каждый объект из БД в компонент <Marker> */}
{/* markers — массив объектов маркеров, который пришёл из базы данных SQLite через пропсы.
.map(...) — встроенный метод массива в JavaScript. Он проходит по каждому элементу массива по очереди и возвращает новый массив (в нашем случае — массив готовых компонентов <Marker /> для отрисовки на карте).
(marker) — параметр стрелочной функции: временная переменная, в которую на каждом шаге цикла попадает один конкретный объект маркера из массива markers. */}
            {markers.map((marker) => (
                <Marker
                    // Уникальный ключ для алгоритма сверки React (используем первичный ключ id из SQLite)
                    key={marker.id}//key — специальный системный проп React (обязателен при создании элементов через .map()). Он помогает React отличать одну булавку от другой при обновлении списка, чтобы перерисовывать только изменившиеся метки.
                    // Задаём географическую позицию булавки на карте (двойные скобки: JS-выражение -> объект координат)
                    coordinate={{
                        latitude: marker.latitude,
                        longitude: marker.longitude,
                    }}
                    // Обработчик нажатия на булавку: оборачиваем в стрелочную функцию () => ...,
                    // чтобы onMarkerPress(marker.id) вызвался только при клике, а не сразу при отрисовке
                    //стрелочная функция-обёртка без аргументов нужна, чтобы функция справа вызвалась только в момент клика по булавке (если написать просто onPress={onMarkerPress(marker.id)}, она сработает сразу при загрузке карты, ещё до нажатия).
                    //onMarkerPress(marker.id) — вызов родительской функции из app/index.tsx с передачей ей id именно этой нажатой булавки (чтобы роутер открыл экран деталей /marker/[id]).
                    onPress={() => onMarkerPress(marker.id)}
                />
            ))}
        </MapView>
    );
}

// Таблица стилей компонента
const styles = StyleSheet.create({
    // flex: 1 растягивает карту на 100% доступной ширины и высоты родительского контейнера
    map: { flex: 1 },
});