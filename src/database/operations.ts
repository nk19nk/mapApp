// Импортируем библиотеку для работы с базой данных SQLite
import * as SQLite from 'expo-sqlite';
// Импортируем типы данных (интерфейсы), чтобы TypeScript знал, как выглядят маркеры и картинки
import { MarkerData, MarkerImage } from '@/types';

// Создаем удобный псевдоним (алиас) DB для длинного типа SQLite.SQLiteDatabase,
// чтобы не писать его каждый раз целиком в аргументах функций
type DB = SQLite.SQLiteDatabase;

/**
 * Создает новый маркер в базе данных.
 * Возвращает уникальный ID (число) только что созданного маркера.
 */

//export — разрешает использовать (импортировать) эту функцию в других файлах проекта.
//async — делает функцию асинхронной(она не блокирует приложение во время работы с базой и позволяет использовать внутри себя команду await).
//db: DB — первый аргумент(входящее значение) во всех функциях.Это передача готового подключения к базе данных.
//Promise(Обещание) — означает, что функция вернет результат не мгновенно, а как только закончит работу с базой данных.
//=> — «стрелка», которая отделяет список аргументов от самого тела функции(кода, который пойдет дальше в скобках {}).
//: Promise<number> — указывает, что после выполнения запроса база данных вернет number (число).
export const addMarker = async (db: DB, latitude: number, longitude: number): Promise<number> => {
//await — заставляет код дождаться завершения операции работы с базой данных, прежде чем идти дальше.
//db — наша переменная, в которой хранится подключение к SQLite.
//.runAsync(...) — метод для выполнения SQL - запросов, которые изменяют данные(добавляют, обновляют или удаляют строки: INSERT, UPDATE, DELETE), но не возвращают таблицу в ответ.
    const result = await db.runAsync(
        // SQL-запрос на добавление. Знаки вопроса (?) используются для защиты от SQL-инъекций.
        // Движок сам безопасно подставит значения из следующих аргументов вместо вопросов.
        'INSERT INTO markers (latitude, longitude) VALUES (?, ?)',
        latitude,
        longitude
    );
    // Возвращаем ID новой добавленной строки (он генерируется базой автоматически благодаря AUTOINCREMENT)
    return result.lastInsertRowId;
};

/**
 * Удаляет маркер по его номеру и все связанные с ним изображения.
 * Использует транзакцию для безопасности данных.
 */

//id: number — аргумент, принимающий ID маркера, который нужно удалить (число).
//: Promise<void> — void переводится как «пустота». Это означает, что функция выполнит свою работу(удалит запись), но не вернет вам никаких данных в ответ.
export const deleteMarker = async (db: DB, id: number): Promise<void> => {
    // withTransactionAsync гарантирует, что оба запроса на удаление выполнятся как единое целое.
    // Если на удалении маркера произойдет сбой, удаление картинок откатится назад.
    //.withTransactionAsync — метод запуска безопасной транзакции. Все SQL-запросы внутри нее выполняются как единый пакет. Если один запрос из пакета завершится с ошибкой, остальные тоже будут отменены (произойдет "откат", чтобы база не сломалась).
    await db.withTransactionAsync(async () => {
        // Сначала удаляем все картинки, привязанные к этому маркеру (по marker_id)
        await db.runAsync('DELETE FROM marker_images WHERE marker_id = ?', id);
        // Затем удаляем сам маркер (по его id)
        await db.runAsync('DELETE FROM markers WHERE id = ?', id);
    });
};

/**
 * Получает список всех маркеров из базы данных для отрисовки на карте.
 */

//: Promise<MarkerData[]> — функция обещает вернуть массив ([]) объектов. Каждый объект внутри массива будет иметь строгую структуру MarkerData (то есть у каждого будут id, latitude и longitude).
export const getMarkers = async (db: DB): Promise<MarkerData[]> => {
    // getAllAsync метод, который выполняет SQL-запрос на чтение (SELECT) и просит базу выдать сразу все найденные строки в виде массива
    // <MarkerData> подсказывает TypeScript, что каждая строка в массиве будет иметь структуру маркера. дженерик (подсказка для TypeScript). Сообщает, что массив будет состоять не просто из непонятных строк, а из объектов со строгой структурой маркера (где есть id, latitude, longitude).
    return await db.getAllAsync<MarkerData>('SELECT * FROM markers ORDER BY id');
};

/**
 * Добавляет новую ссылку на изображение (uri) и привязывает её к конкретному маркеру.
 */

//markerId: number — аргумент, числовой ID маркера, к которому мы хотим привязать фото.
//uri: string — аргумент, локальный путь к файлу картинки на телефоне.Слово string означает, что это должен быть текст(строка).
//: Promise<void> — функция отработает и ничего не вернет(пустота).
export const addImage = async (db: DB, markerId: number, uri: string): Promise<void> => {
    // Вставляем id родительского маркера и локальный путь к файлу картинки на телефоне
    await db.runAsync('INSERT INTO marker_images (marker_id, uri) VALUES (?, ?)', markerId, uri);
};

/**
 * Удаляет конкретное изображение из базы данных по его ID.
 */
export const deleteImage = async (db: DB, id: number): Promise<void> => {
    // Удаляем только одну строку из таблицы картинок
    await db.runAsync('DELETE FROM marker_images WHERE id = ?', id);
};

/**
 * Получает список всех изображений, принадлежащих конкретному маркеру.
 */

//markerId: number — аргумент. Мы просим базу найти картинки только для этого конкретного маркера.
//: Promise<MarkerImage[]> — функция обещает выдать массив([]), состоящий из объектов типа MarkerImage(id, uri, marker_id).
export const getMarkerImages = async (db: DB, markerId: number): Promise<MarkerImage[]> => {
    // Запрашиваем строки из таблицы marker_images, фильтруя их по marker_id
//db.getAllAsync — запрос на получение всех строк, удовлетворяющих нашему SQL-запросу (в данном случае это будут все картинки для конкретного маркера).
//<MarkerImage> — дженерик.Сообщает TypeScript, что полученные данные будут иметь структуру картинки маркера(где есть id, marker_id, uri).
    return await db.getAllAsync<MarkerImage>(
        'SELECT * FROM marker_images WHERE marker_id = ? ORDER BY id',
        markerId
    );
};