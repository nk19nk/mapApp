import * as SQLite from 'expo-sqlite';

//Эта строка создает публичную асинхронную функцию initDatabase.
//Она ничего не принимает на вход(), работает в фоновом режиме(async) и обещает(Promise) 
//вернуть готовое и открытое подключение к базе данных(SQLite.SQLiteDatabase) после завершения своей работы.
// export (экспортировать) — команда, которая делает эту функцию доступной для использования в других файлах проекта.
// Благодаря ей мы можем написать import { initDatabase } from '@/database/schema' в другом месте.

//const(константа) — объявляет переменную, которую нельзя будет переопределить позже.Мы гарантируем, что под этим именем всегда будет лежать именно эта функция.

//initDatabase — название нашей переменной(и самой функции).Переводится как «инициализировать базу данных».

//= — оператор присваивания.Мы кладем всё, что написано справа от него, в переменную initDatabase.

//async(асинхронность) — ключевое слово, говорящее о том, что функция выполняется не мгновенно, а требует времени(например, открытие файла базы данных).
// Оно позволяет использовать внутри функции команду await (подождать).

//() — место для аргументов(входящих данных) функции.Они пустые, потому что для запуска инициализации базе не нужны никакие дополнительные данные снаружи.

//: — синтаксис TypeScript.Всё, что идет после двоеточия до стрелки =>, описывает то, что именно эта функция вернет в качестве результата.

//Promise(обещание / промис) — стандартный объект JavaScript для асинхронных операций.Поскольку функция async, она не может вернуть готовую базу мгновенно, 
// она возвращает «обещание», что база данных когда - нибудь скоро будет готова.

//<SQLite.SQLiteDatabase> — синтаксис дженериков(уточнений) в TypeScript.Он уточняет, что именно лежит внутри «обещания».

// SQLite — это библиотека expo - sqlite, которую мы импортировали в начале файла.

//SQLiteDatabase — это специальный тип данных из этой библиотеки, который описывает готовый объект подключенной базы данных.

// => (стрелка) — синтаксис «стрелочной функции» в JavaScript.Она визуально отделяет входящие аргументы и типы(слева) от самого тела функции 
// с кодом(которое пойдет дальше в фигурных скобках {}).
export const initDatabase = async (): Promise<SQLite.SQLiteDatabase> => {
    // 1. Открываем базу файл базы данных markers.db на телефоне и сохраняет управление им в переменную db.
//Если файла ещё нет(при первом запуске приложения), он создается автоматически.
//Команда await заставляет код подождать — программа не пойдет дальше, пока файл полностью не откроется и не будет готов к работе.
    const db = await SQLite.openDatabaseAsync('markers.db');//переменная с активным подключением к базе данных

    // 2. Включаем внешние ключи (Обязательно для ON DELETE CASCADE). Включает поддержку связей между таблицами. Это нужно, чтобы при удалении маркера его картинки удалялись автоматически.
//.execAsync(...) — метод(«выполнить асинхронно»), который отправляет SQL - команду, но не ждет от неё возврата каких - либо данных
    await db.execAsync('PRAGMA foreign_keys = ON;');

    // 3. Получаем текущую версию базы (требование задания)
//db.getFirstAsync — метод, который отправляет запрос в базу и берет ровно одну(самую первую) строку из ответа.
//<{ user_version: number }> — это подсказка(дженерик) для TypeScript.Мы заранее объясняем коду, что ответ будет выглядеть как объект с одним полем user_version, и там будет лежать число(number).
//'PRAGMA user_version' — SQL - запрос, который просит базу выдать свой текущий номер версии(насколько она обновлена).
    const row = await db.getFirstAsync<{ user_version: number }>('PRAGMA user_version');//Запрашивает у базы данных её текущую версию (насколько она обновлена).
    const currentVersion = row?.user_version ?? 0;//Сохраняет эту версию в переменную. Если база совершенно новая и версии еще нет, устанавливает значение 0.

    // 4. Если база пустая — создаем таблицы в одной транзакции
    if (currentVersion < 1) {
        //.withTransactionAsync — метод «запустить транзакцию». Транзакция — это защитная оболочка. Все команды внутри неё выполняются как одно целое (по принципу «всё или ничего»).
        await db.withTransactionAsync(async () => {
            //db.execAsync — метод «выполнить SQL-запрос асинхронно». Сюда вы передаете текстовые SQL-команды (например, CREATE TABLE), и этот метод отправляет их напрямую в движок SQLite.
            await db.execAsync(`
                CREATE TABLE IF NOT EXISTS markers (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    latitude REAL NOT NULL,
                    longitude REAL NOT NULL,
                    created_at DATETIME DEFAULT CURRENT_TIMESTAMP
                );
                CREATE TABLE IF NOT EXISTS marker_images (
                    id INTEGER PRIMARY KEY AUTOINCREMENT,
                    marker_id INTEGER NOT NULL,
                    uri TEXT NOT NULL,
                    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
                    FOREIGN KEY (marker_id) REFERENCES markers (id) ON DELETE CASCADE
                );
            `);
            await db.execAsync('PRAGMA user_version = 1;');//Если всё прошло успешно, последняя строчка записывает в память базы цифру 1 — метку о том, что таблицы созданы и структура обновлена до первой версии.
        });
    }

    return db;
};