// Импортируем инструменты React:
// createContext — для создания глобального хранилища (контекста)
// useContext — для чтения данных из контекста в других компонентах
// useEffect — для запуска побочных эффектов (открытие БД при старте)
// useState — для хранения состояний (подключение к БД, загрузка, ошибка)
// ReactNode — тип TypeScript для любых дочерних элементов, которые можно вложить внутрь компонента
import { createContext, useContext, useEffect, useState, ReactNode } from 'react';
// Импортируем библиотеку SQLite от Expo
import * as SQLite from 'expo-sqlite';
// Импортируем функцию инициализации базы (открытие файла и создание таблиц)
import { initDatabase } from '@/database/schema';
// Импортируем все CRUD-операции из operations.ts в один объект ops (ops.addMarker, ops.getMarkers и т.д.)
import * as ops from '@/database/operations';
// Импортируем типы данных маркера и картинки
import { MarkerData, MarkerImage } from '@/types';

// Интерфейс (шаблон), описывающий, какие именно функции и состояния
// будут доступны любому экрану, подключившемуся к этому контексту.
// Обратите внимание: здесь методы уже НЕ требуют передавать db — контекст подставит её сам.
//{ ... } — внутри перечисляются все свойства и функции, которые будет отдавать контекст:
interface DatabaseContextType {
    //имя метода, принимаемые аргументы с типами, стрелка => (означает «возвращает»), Promise<number> (обещание вернуть число — ID маркера).
    addMarker: (latitude: number, longitude: number) => Promise<number>; // Добавить маркер и вернуть его ID
    deleteMarker: (id: number) => Promise<void>;// Удалить маркер по ID (возвращает обещание без результата (void — пустота).
    getMarkers: () => Promise<MarkerData[]>;// Получить массив всех маркеров (аргументов нет (()), возвращает обещание с массивом ([]) объектов MarkerData.
    addImage: (markerId: number, uri: string) => Promise<void>;// Привязать фото (путь uri) к маркеру
    deleteImage: (id: number) => Promise<void>;// Удалить конкретное фото по ID
    getMarkerImages: (markerId: number) => Promise<MarkerImage[]>;// Получить все фото конкретного маркера
    isLoading: boolean;// Флаг: идёт ли сейчас загрузка/открытие БД
    error: Error | null;// Объект ошибки, если БД не смогла открыться (или null)(вертикальная черта | означает «ИЛИ»: здесь может лежать либо объект ошибки Error, либо пустота null)
    retry: () => void;// Функция повторной попытки подключения к БД
}

// Создаём сам объект контекста.
// По умолчанию он равен null (если кто-то попытается обратиться к нему вне DatabaseProvider)
// createContext — встроенная функция React для создания «общего хранилища», доступного на любом уровне вложенности компонентов.
// < DatabaseContextType null |> — дженерик для TypeScript: говорим, что внутри контекста будет либо наш объект с методами БД, либо null.
// (null) — значение по умолчанию(оно сработает, только если кто - то попытается прочитать контекст вне DatabaseProvider).
const DatabaseContext = createContext<DatabaseContextType | null>(null);

// Компонент-провайдер (обёртка). Им оборачивается всё приложение в _layout.tsx,
// чтобы все вложенные экраны ({ children }) получили доступ к одной общей базе данных.
// export — делает компонент доступным для импорта в других файлах(в app / _layout.tsx).
// function DatabaseProvider — объявление React - компонента в виде функции.
// ({ children }) — деструктуризация пропсов: мы забираем специальное свойство children(всё, что вложено внутрь тегов<DatabaseProvider>...</DatabaseProvider >).
// : { children: ReactNode } — типизация пропсов: ReactNode означает «любой допустимый элемент React» (экраны, текст, другие компоненты).
export function DatabaseProvider({ children }: { children: ReactNode }) {
    // Состояние для хранения открытого подключения к SQLite (пока не открылось — null)
// [db, setDb] — деструктуризация массива.Хук useState всегда возвращает массив ровно из двух элементов, и мы сразу раскладываем их по двум переменным:
// db — текущее значение состояния(само подключение к базе данных).
// setDb — функция - сеттер, вызов которой записывает новое значение в db и заставляет React перерисовать компонент.
// = — оператор присваивания.
// useState — встроенный хук React для создания состояния
//<SQLite.SQLiteDatabase null |> — дженерик(подсказка для TypeScript).Он нужен здесь обязательно, потому что стартовое значение null, и без подсказки TypeScript подумал бы, что в db всегда будет только null:
//SQLite.SQLiteDatabase — тип объекта открытой базы данных из библиотеки expo - sqlite.
//| — логическое «ИЛИ» (union type).
//null — тип «пустота» (пока база ещё не открылась).
//(null) — начальное значение состояния.В момент запуска приложения база ещё не открыта, поэтому в db лежит null.
    const [db, setDb] = useState<SQLite.SQLiteDatabase | null>(null);
    // Состояние для хранения возможной ошибки инициализации БД
// const [error, setError] — деструктуризация:
// error — текущая ошибка (если она произошла при открытии БД).
// setError — функция для записи новой ошибки или её сброса.
// = useState — вызов хука состояния.
// < Error null |> — дженерик TypeScript: в состоянии может храниться либо стандартный объект ошибки Error, либо(|) пустота null.
// (null) — начальное значение.При старте ошибок ещё нет, поэтому null.
    const [error, setError] = useState<Error | null>(null);
    // Флаг загрузки: изначально true, пока база открывается и создаёт таблицы
// const [isLoading, setIsLoading] — деструктуризация:
// isLoading — логический флаг («идёт ли сейчас загрузка ?»).
// setIsLoading — функция для переключения этого флага.
// = useState(true) — вызов хука с начальным значением true(«да, загрузка идёт»).
// Почему здесь нет угловых скобок<boolean> ? TypeScript достаточно умный, чтобы сам автоматически вывести тип boolean по переданному значению true.
    const [isLoading, setIsLoading] = useState(true);
    // Счётчик попыток подключения. Нужен для кнопки «Повторить» (retry):
    // изменение этого числа заставит useEffect ниже запуститься заново
// const [attempt, setAttempt] — деструктуризация:
// attempt — числовой счётчик попыток подключения к базе данных.
// setAttempt — функция для увеличения этого счётчика (используется в retry).
// = useState(0) — вызов хука с начальным значением 0. TypeScript автоматически определяет тип как number.
    const [attempt, setAttempt] = useState(0);

    // Хук запускается при первом монтировании провайдера и каждый раз, когда меняется attempt
//встроенный хук React, который запускает побочный эффект (в нашем случае — асинхронную работу с базой данных) после отрисовки компонента.
    useEffect(() => {
        // Флаг отмены: защищает от утечек памяти и попыток обновить состояние,
        // если компонент успел закрыться до завершения асинхронного открытия БД
//Это флаг-предохранитель на случай, если пользователь закроет приложение раньше, чем база успеет открыться.
//= false; — начальное значение(«нет, операция не отменена»).
        let cancelled = false;
        // Локальная переменная для хранения ссылки на открытую БД, чтобы корректно закрыть её в функции очистки(Она нужна именно локально внутри useEffect, чтобы функция очистки внизу точно знала, какое соединение закрывать.)
// : SQLite.SQLiteDatabase | null — тип для TypeScript: здесь может быть либо объект открытой базы, либо null.
// = null; — стартовое значение(пока база не открылась).
        let database: SQLite.SQLiteDatabase | null = null;

        // Перед началом подключения включаем загрузку и сбрасываем прошлую ошибку
        setIsLoading(true);//вызывает функцию-сеттер состояния и включает индикатор загрузки.
        setError(null);//сбрасывает предыдущую ошибку (важно при повторной попытке через retry).

        // Запускаем асинхронную инициализацию базы данных (PRAGMA, транзакция создания таблиц)
        initDatabase()//Вызов нашей асинхронной функции из schema.ts. Она не блокирует интерфейс, а сразу возвращает Promise (обещание), к которому ниже по цепочке прикреплены три метода: .then, .catch и .finally.
// .then(...) — метод Promise(«затем»).Код внутри выполнится, только если initDatabase() завершилась успешно.
// (openedDb) => { — стрелочная функция, в параметр openedDb автоматически приходит результат работы initDatabase()(открытый объект базы данных).
        .then((openedDb) => {
                // Если за время открытия БД компонент уже был размонтирован — сразу закрываем соединение и выходим
                if (cancelled) {
                    openedDb.closeAsync();//если да, то сразу асинхронно закрываем только что открытое соединение, чтобы не было утечки памяти.
                    return;//мгновенно выходим из .then, не обновляя состояние React.
                }
                // Если всё в порядке — сохраняем открытую базу в локальную переменную и в state React
            database = openedDb;//Записываем открытую базу в нашу локальную переменную database (пригодится позже в функции очистки).
            setDb(openedDb);//Сохраняем открытую базу в состояние React (db), чтобы все экраны приложения могли начать делать к ней запросы.
            })
            .catch((e) => {
                // Если произошла ошибка (и компонент ещё активен) — сохраняем её в state.
                // Если прилетела не стандартная Error, оборачиваем её в new Error(String(e))
// if (!cancelled) — Обновляем состояние ошибки, только если компонент всё ещё существует.
//     setError(...) — сохраняет ошибку в состояние React.
// e instanceof Error ? e : new Error(String(e)) — тернарный оператор(условие ? если_да : если_нет):
// e instanceof Error — оператор instanceof проверяет, является ли e настоящим объектом класса Error.
// ? e — если да, передаём e как есть.
// : new Error(String(e)) — если прилетела просто строка или число, превращаем это в текст через String(e) и оборачиваем в полноценный объект new Error(...).
                if (!cancelled) setError(e instanceof Error ? e : new Error(String(e)));
            })
//.finally(...) — метод Promise(«в конце концов»).Выполнится гарантированно в любом случае — и после успеха(.then), и после ошибки(.catch).
// () => { ... } — функция без аргументов.
//     if(!cancelled) setIsLoading(false); — если компонент не закрыт, выключаем индикатор загрузки.
            .finally(() => {
                // В любом случае (успех или ошибка) выключаем индикатор загрузки, если компонент ещё жив
                if (!cancelled) setIsLoading(false);
            });

        // Функция очистки: React вызовет её при размонтировании провайдера или перед перезапуском useEffect
        //return — возвращает из useEffect специальную функцию очистки (cleanup). React автоматически вызовет её в двух случаях: когда DatabaseProvider исчезнет с экрана, или прямо перед тем, как useEffect перезапустится заново.
        return () => {
            cancelled = true;// Помечаем текущую операцию как отменённую(Переключает флаг отмены в true, чтобы незавершённые .then/.catch/.finally не пытались менять состояние уже закрытого компонента.)
// database — обращение к локальной переменной с открытой БД.
// ?. — оператор опциональной цепочки.Означает: «если database не null, вызови метод справа; если null, просто пропусти эту строку без ошибки».
// closeAsync() — асинхронно закрывает файл SQLite.
            database?.closeAsync();// Безопасно закрываем файл БД, если он успел открыться (?.)
        };
        //, [attempt] — второй аргумент useEffect (массив зависимостей). Говорит React: «выполни этот эффект при первом запуске и перезапускай его каждый раз, когда изменится значение переменной attempt».
    }, [attempt]); // Массив зависимостей: эффект перезапустится только при изменении attempt

    // Вспомогательная защитная функция.
    // Гарантирует, что перед выполнением любого SQL-запроса база точно открыта (не null).
    const getDb = () => {//функции «получить базу данных»
        //!db) — Так как db может быть null, !db станет true, если база ещё не открыта.
        //throw — выбрасывает ошибку и мгновенно прерывает выполнение функции.
        //new Error('База данных не подключена') — создаёт новый объект стандартной ошибки с понятным текстом.
        if (!db) throw new Error('База данных не подключена');
        // возвращает результат из функции.
        //db — гарантированно открытое подключение к SQLite(TypeScript после проверки if (!db) точно знает, что здесь db уже не null).
        return db;
    };

    // Собираем итоговый объект value со всеми методами и состояниями, который получат дочерние компоненты через useDatabase()
//: DatabaseContextType — строгая типизация TypeScript: объект value обязан содержать все поля и методы, описанные в интерфейсе DatabaseContextType в начале файла.
    const value: DatabaseContextType = {
        // Оборачиваем функции из operations.ts: автоматически подставляем им getDb() первым аргументом,
        // чтобы на экранах можно было писать просто addMarker(lat, lon), не думая о подключении к БД
// addMarker — имя свойства- метода в объекте value.
// : — связывает имя свойства с функцией справа.
// (latitude, longitude) — параметры, которые передаст экран(например, index.tsx), когда вызовет addMarker.Их типы(number) TypeScript подтягивает автоматически из DatabaseContextType.
// => — стрелка короткого возврата(автоматически возвращает результат выражения справа, то есть Promise<number>).
// ops.addMarker(...) — вызов реальной SQL - функции из файла operations.ts(импортированного как ops).
// getDb() — вызываем нашу защитную функцию, чтобы получить открытое подключение к БД и передать его первым аргументом.
// latitude, longitude — прокидываем координаты дальше без изменений.
        addMarker: (latitude, longitude) => ops.addMarker(getDb(), latitude, longitude),
        deleteMarker: (id) => ops.deleteMarker(getDb(), id),
        getMarkers: () => ops.getMarkers(getDb()),
        addImage: (markerId, uri) => ops.addImage(getDb(), markerId, uri),
        deleteImage: (id) => ops.deleteImage(getDb(), id),
        getMarkerImages: (markerId) => ops.getMarkerImages(getDb(), markerId),
        isLoading, // Передаём текущий статус загрузки
        error,     // Передаём текущую ошибку (если есть)
        // Функция повторной попытки: увеличивает счётчик attempt на 1, что автоматически перезапускает useEffect
// retry — имя функции(«повторить»).
// () => — стрелочная функция без аргументов.
// setAttempt(attempt + 1) — вызывает сеттер состояния attempt, увеличивая счётчик на единицу.Поскольку attempt указан в массиве зависимостей useEffect, это автоматически перезапустит подключение к базе.
        retry: () => setAttempt(attempt + 1),
    };

    return (
        // Оборачиваем всё дерево дочерних компонентов ({children}) в Provider,
        // раздавая им собранный объект value
// <DatabaseContext.Provider ...> — встроенный компонент-поставщик, который автоматически создаётся внутри любого React Context. Он «транслирует» данные вниз по дереву компонентов.
//value={value} — передаём обязательный проп value (слева — имя пропа, внутри фигурных скобок {value} — наша переменная-объект с методами и состояниями).
//{children} — фигурные скобки в JSX означают «вставь сюда JavaScript-выражение». Здесь отрисуются все дочерние экраны приложения, которые обёрнуты в <DatabaseProvider> в файле _layout.tsx
        <DatabaseContext.Provider value={value}>{children}</DatabaseContext.Provider>
    );
}

// Кастомный хук — удобная обёртка над useContext для использования на экранах (index.tsx, [id].tsx)
export function useDatabase() {//useDatabase — имя хука. В React есть строгое правило: имена всех хуков обязаны начинаться со слова use, иначе React не сможет отслеживать правила их вызова.
    // Достаём значение value из ближайшего DatabaseContext.Provider выше по дереву
// useContext(...) — встроенный хук React.Он «поднимается» вверх по дереву компонентов, находит ближайший < DatabaseContext.Provider > и забирает из него объект value(со всеми методами БД, isLoading, error и retry).
// DatabaseContext — тот самый объект контекста, который мы создали в начале файла через createContext.
    const context = useContext(DatabaseContext);
    // Защита от ошибки разработчика: если хук вызвали вне обёртки <DatabaseProvider>, сразу выбрасываем понятную ошибку
    //По умолчанию наш контекст равен null. Если кто-то забудет обернуть приложение в <DatabaseProvider> и вызовет useDatabase(), то context окажется null, а !context станет true.
    if (!context) {
        //new Error(...) — создаёт стандартный объект ошибки с понятным текстом-подсказкой для разработчика, чтобы сразу было ясно, что пошло не так.
        throw new Error('useDatabase нужно использовать внутри DatabaseProvider');
    }
    // Возвращаем готовый объект с методами и состояниями базы данных
    //возвращает результат тому экрану, который вызвал useDatabase().
    //context — наш готовый объект с методами базы данных. Благодаря проверке if (!context) выше, TypeScript точно знает, что здесь context уже гарантированно не null, а полноценный DatabaseContextType.
    return context;
}

// Зачем вообще нужен этот хук, если можно вызывать useContext(DatabaseContext) напрямую ?
//Меньше кода на экранах: достаточно импортировать один useDatabase, вместо того чтобы каждый раз импортировать и useContext, и DatabaseContext.
// Удобство для TypeScript: без этой проверки на каждом экране пришлось бы вручную проверять if (context !== null) перед каждым вызовом addMarker или getMarkers.